    a.ldr_r(1, 10, 9, shift=2)         # divisor = pow10[index]
    a.mov_i(2, 0)                      # digit
    a.label('dn_sub')
    a.cmp_r(4, 1)
    a.b('dn_sub_done', 'lt')
    a.sub_r(4, 4, 1)
    a.add_i(2, 2, 1)
    a.b('dn_sub')

    a.label('dn_sub_done')
