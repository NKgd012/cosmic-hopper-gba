FONT_ORDER = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ '


def font_data():
    out = bytearray()
    for ch in FONT_ORDER:
        for row in FONT_ART[ch]:
            bits = 0
            for i, c in enumerate(row):     # i = 0 is the leftmost pixel
                if c == '#':
                    bits |= 1 << i
            out.append(bits)
    return bytes(out)


def lcg(st):
    return (st * 1103515245 + 12345) & 0xFFFFFFFF


def star_data(n=48):
    """Packed (y << 8) | x stars spread over a 256 px tall band, so they can
    wrap with `(y - camera/2) & 255` while the player climbs."""
    st = 0x5EED1234
    out = bytearray()
    for _ in range(n):
        st = lcg(st)
        x = 2 + ((st >> 8) & 0xFF) % 236
        y = (st >> 16) & 0xFF
        out += struct.pack('<I', ((y & 0xFF) << 8) | (x & 0xFF))
    return bytes(out)


def planet_table(radius=22):
    """Half width of the planet disk for every row (top to bottom)."""
    rows = bytearray()
    for dy in range(-radius, radius + 1):
        w = int((radius * radius - dy * dy) ** 0.5)
        rows.append(w)
    return bytes(rows)


