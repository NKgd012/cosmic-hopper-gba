    # ======================================================================
    # draw_number(value r0, x r1, y r2, colour r3) - 3 to 7 digits
    # ======================================================================
    a.label('draw_number')
    a.push(0x4FF0)                     # {r4-r11, lr}
    a.mov_r(4, 0)                      # value
    a.mov_r(5, 1)                      # x
    a.mov_r(6, 2)                      # y
    a.mov_r(7, 3)                      # colour
    a.mov_i(8, 0)                      # started printing?
    a.mov_i(9, 0)                      # digit index
    a.ldr_lit(10, tab_pow10)

