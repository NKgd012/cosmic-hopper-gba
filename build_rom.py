    # ======================================================================
    # draw_astronaut(sx r0, sy r1)
    # ======================================================================
    a.label('draw_astronaut')
    a.push(0x40F0)
    a.mov_r(6, 0)
    a.mov_r(7, 1)

    a.add_i(0, 6, 0)                   # backpack
    a.add_i(1, 7, 6)
    a.mov_i(2, 3)
    a.mov_i(3, 8)
    a.ldr_lit(4, C_PACK)
    a.bl('blit_rect')

    a.add_i(0, 6, 3)                   # body
    a.add_i(1, 7, 5)
    a.mov_i(2, 8)
    a.mov_i(3, 9)
    a.ldr_lit(4, C_BODY)
    a.bl('blit_rect')

    a.add_i(0, 6, 3)                   # helmet
    a.add_i(1, 7, 0)
    a.mov_i(2, 8)
    a.mov_i(3, 5)
    a.ldr_lit(4, C_BODY)
