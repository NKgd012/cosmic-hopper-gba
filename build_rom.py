"""
COSMIC HOPPER for Game Boy Advance - built from scratch, without devkitPro.

The ROM is generated by the tiny ARMv4T assembler below and written as a raw
.gba image (header + ARM code + data).  No SDK, no C compiler, no libraries.

    python build_rom.py        ->  cosmic-hopper.gba

Hardware features used:
  * video mode 3 (240x160, 16bpp direct colour framebuffer)
  * KEYINPUT polling (D-pad + START)
  * VCOUNT polling for a stable 60 Hz game loop
Nothing else: no BIOS calls, no interrupts, no DMA - so it boots on VBA-M,
gpSP, mGBA, no$gba, real hardware, etc.
"""

