    a.b('dn_draw', 'ne')               # already inside the number
    a.cmp_i(2, 0)
    a.b('dn_begin', 'ne')              # first non-zero digit
    a.mov_i(3, 7)
    a.sub_r(3, 3, 9)                   # digits left, including this one
    a.cmp_i(3, 3)
    a.b('dn_skip', 'gt')               # always show at least 3 digits

    a.label('dn_begin')
    a.mov_i(8, 1)

    a.label('dn_draw')
    a.mov_r(0, 2)
    a.add_i(0, 0, 0x30)
    a.mov_r(1, 5)
    a.mov_r(2, 6)
    a.mov_r(3, 7)
    a.bl('draw_char')
    a.add_i(5, 5, 8)

    a.label('dn_skip')
    a.add_i(9, 9, 1)
    a.cmp_i(9, 7)
    a.b('dn_loop', 'lt')
    a.pop(0x8FF0)

    # ======================================================================
    code, pool, data = a.finish()

    rom = bytearray(b'\xFF' * ROM_SIZE)
    header = make_header()
    rom[0:0xC0] = header
    blob = code + pool + data
    if CODE_OFF + len(blob) > ROM_SIZE:
        raise RuntimeError("ROM too small")
    rom[CODE_OFF:CODE_OFF + len(blob)] = blob

    info = {
        'labels': a.labels,
        'code_size': len(code),
        'pool_size': len(pool),
        'data_size': len(data),
        'rom_size': len(rom),
        'data': data,
    }
    return bytes(rom), info


