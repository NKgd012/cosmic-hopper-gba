def build():
    a = Asm(CODE_BASE)

    tab_sky = Table(struct.pack('<10I', *SKY))
    tab_stars = Table(star_data())
    tab_planet = Table(planet_table())
    tab_font = Table(font_data())
    tab_score = Table(b'SCORE\x00')
    tab_title1 = Table(b'COSMIC\x00')
    tab_title2 = Table(b'HOPPER\x00')
    tab_press = Table(b'PRESS START\x00')
    tab_over = Table(b'GAME OVER\x00')
    tab_hint = Table(b'LEFT RIGHT MOVE\x00')
    tab_pow10 = Table(struct.pack('<7I', 1000000, 100000, 10000, 1000, 100, 10, 1))

    # ======================================================================
    # entry
    # ======================================================================
    a.label('start')
    a.ldr_lit(13, 0x03007F00)          # sp
    a.ldr_lit(1, 0x04000000)
    a.ldr_lit(0, 0x0403)               # mode 3 + BG2 on
    a.strh(0, 1, 0)                    # DISPCNT

    a.bl('reset_game')
    a.ldr_lit(0, V_STATE)
    a.mov_i(1, 2)                      # title screen
    a.str(1, 0, 0)
    a.bl('draw_title')

    # ======================================================================
    # main loop (one iteration == one video frame)
    # ======================================================================
    a.label('l_main')
    a.bl('wait_vblank')
    a.bl('read_keys')

    a.ldr_lit(0, V_STATE)
    a.ldr(0, 0, 0)
    a.cmp_i(0, 2)
    a.b('l_title', 'eq')
    a.cmp_i(0, 1)
    a.b('l_dead', 'eq')

    a.bl('update_game')
    a.bl('draw_game')
    a.b('l_main')

    # ======================================================================
    # title screen
    # ======================================================================
    a.label('l_title')
    a.ldr_lit(0, V_EDGE)
    a.ldr(0, 0, 0)
    a.tst_i(0, 8)                      # START
    a.b('l_main', 'eq')
    a.bl('reset_game')
    a.b('l_main')

    # ======================================================================
    # game over
    # ======================================================================
    a.label('l_dead')
    a.bl('draw_gameover')
    a.ldr_lit(0, V_EDGE)
    a.ldr(0, 0, 0)
    a.tst_i(0, 8)                      # START
    a.b('l_main', 'eq')
    a.bl('reset_game')
    a.b('l_main')

    # ======================================================================
    # wait_vblank: wait for the start of VBlank (VCOUNT == 160)
    # ======================================================================
    a.label('wait_vblank')
    a.ldr_lit(12, 0x04000000)
    a.label('wv_low')
    a.ldrh(0, 12, 6)                   # VCOUNT
    a.cmp_i(0, 160)
    a.b('wv_low', 'ne')
    a.label('wv_high')
    a.ret()

    # ======================================================================
    # read_keys: D-pad -> direction, START -> rising edge
    # ======================================================================
    a.label('read_keys')
    a.push(0x4010)                     # {r4, lr}
    a.ldr_lit(1, 0x04000000)
    a.ldr(0, 1, 0x130)                 # KEYINPUT (active low)
    a.mvn_r(0, 0)
    a.and_i(0, 0, 0xFF)                # buttons + START
    # 0xFF means "every button at once", which the hardware can never produce:
    # it is what an uninitialised keypad register looks like on some emulators.
    a.cmp_i(0, 0xFF)
    a.mov_i(0, 0, cond='eq')

    a.ldr_lit(1, V_PREV)
    a.ldr(2, 1, 0)
    a.str(0, 1, 0)

    # START is accepted only after (a) at least one frame with nothing pressed
    # since reset, and (b) five consecutive frames of the button being held.
    # The keypad register can hold junk for the first frames after power-on;
    # without this filter it looks like somebody pressed START.
    a.mov_i(3, 0)                      # no edge yet
    a.cmp_i(0, 0)
    a.b('rk_armed', 'ne')

    a.ldr_lit(1, V_ARM)
    a.mov_i(2, 1)
    a.str(2, 1, 0)
    a.ldr_lit(1, V_HOLD)
    a.mov_i(2, 0)
    a.str(2, 1, 0)
    a.b('rk_edge')

    a.label('rk_armed')
    a.ldr_lit(1, V_ARM)
    a.ldr(2, 1, 0)
    a.cmp_i(2, 0)
    a.b('rk_edge', 'eq')

    a.tst_i(0, 8)                      # START
    a.b('rk_hold', 'ne')

    a.ldr_lit(1, V_HOLD)
    a.mov_i(2, 0)
    a.str(2, 1, 0)
    a.b('rk_edge')

    a.label('rk_hold')
    a.ldr_lit(1, V_HOLD)
    a.ldr(2, 1, 0)
    a.add_i(2, 2, 1)
    a.str(2, 1, 0)
    a.cmp_i(2, 5)
    a.mov_i(3, 8, cond='eq')           # one-shot edge on the 5th frame

    a.label('rk_edge')
    a.ldr_lit(1, V_EDGE)
    a.str(3, 1, 0)

    a.mov_i(4, 0)
    a.tst_i(0, 0x10)                   # RIGHT
    a.add_i(4, 4, 1, cond='ne')
    a.tst_i(0, 0x20)                   # LEFT
    a.sub_i(4, 4, 1, cond='ne')
    a.ldr_lit(1, V_DIRX)
    a.str(4, 1, 0)
    a.pop(0x8010)

    # ======================================================================
    # update_game
    # ======================================================================
    a.label('update_game')
    a.push(0x47F0)                     # {r4-r10, lr}
    a.bl('gen_platforms')

    # --- horizontal movement --------------------------------------------
    a.ldr_lit(0, V_DIRX)
    a.ldr(6, 0, 0)
    a.ldr_lit(1, SPEED)
    a.mul(1, 6, 1)
    a.ldr_lit(0, V_PX)
    a.ldr(2, 0, 0)
    a.add_r(2, 2, 1)
    a.cmp_i(2, 0)
    a.mov_i(2, 0, cond='lt')
    a.ldr_lit(1, PX_MAX)
    a.cmp_r(2, 1)
    a.mov_r(2, 1, cond='gt')
    a.str(2, 0, 0)

    # --- remember the previous feet position ----------------------------
    a.ldr_lit(0, V_PY)
    a.ldr(3, 0, 0)
    a.ldr_lit(1, V_PPY)
    a.str(3, 1, 0)

    # --- gravity ---------------------------------------------------------
    a.ldr_lit(0, V_VY)
    a.ldr(7, 0, 0)
    a.add_i(7, 7, GRAV)
    a.ldr_lit(1, VY_MAX)
    a.cmp_r(7, 1)
    a.mov_r(7, 1, cond='gt')
    a.str(7, 0, 0)

    # --- vertical movement ----------------------------------------------
    a.ldr_lit(0, V_PY)
    a.ldr(8, 0, 0)
    a.add_r(8, 8, 7)
    a.str(8, 0, 0)

    # --- landing ---------------------------------------------------------
    a.cmp_i(7, 0)
    a.b('ug_cam', 'le')
    a.bl('land_check')

    # --- camera (only scrolls up, keeps the player around y=56) ----------
    a.label('ug_cam')
    a.ldr_lit(0, V_PY)
    a.ldr(0, 0, 0)
    a.sub_i(0, 0, CAM_OFF)
    a.ldr_lit(1, V_CAM)
    a.ldr(2, 1, 0)
    a.cmp_r(0, 2)
    a.b('ug_best', 'ge')
    a.str(0, 1, 0)

    # --- score = height climbed (1 point / 8 px) -------------------------
    a.label('ug_best')
    a.ldr_lit(0, V_PY)
    a.ldr(0, 0, 0)
    a.mov_shift(0, 0, 2, 8)            # py >> 8
    a.ldr_lit(1, V_BEST)
    a.ldr(2, 1, 0)
    a.cmp_r(0, 2)
    a.b('ug_dead', 'ge')
    a.str(0, 1, 0)
    a.ldr_lit(1, SCORE_BASE)
    a.sub_r(2, 1, 0)
    a.mov_shift(2, 2, 2, 3)            # / 8 (signed)
    a.cmp_i(2, 0)
    a.mov_i(2, 0, cond='lt')
    a.ldr_lit(1, V_SCORE)
    a.str(2, 1, 0)

    # --- death: fell below the screen ------------------------------------
    a.label('ug_dead')
    a.ldr_lit(0, V_PY)
    a.ldr(0, 0, 0)
    a.mov_shift(0, 0, 2, 8)
    a.ldr_lit(1, V_CAM)
    a.ldr(1, 1, 0)
    a.mov_shift(1, 1, 2, 8)
    a.add_i(1, 1, 190)
    a.cmp_r(0, 1)
    a.b('ug_done', 'le')
    a.ldr_lit(0, V_STATE)
    a.mov_i(1, 1)                      # dead
    a.str(1, 0, 0)

    a.label('ug_done')
    a.pop(0x87F0)

    # ======================================================================
    # land_check: bounce when falling through a platform top
    # ======================================================================
    a.label('land_check')
    a.push(0x47F0)
    a.ldr_lit(0, V_VY)
    a.ldr(0, 0, 0)
    a.cmp_i(0, 0)
    a.b('lc_done', 'le')

    a.ldr_lit(0, V_PX)
    a.ldr(0, 0, 0)
    a.mov_shift(0, 0, 2, 8)            # x
    a.ldr_lit(1, V_PY)
    a.ldr(1, 1, 0)
    a.mov_shift(1, 1, 2, 8)
    a.add_i(1, 1, PH)                  # new feet
    a.ldr_lit(2, V_PPY)
    a.ldr(2, 2, 0)
    a.mov_shift(2, 2, 2, 8)
    a.add_i(2, 2, PH)                  # previous feet
    a.ldr_lit(3, V_PLATS)
    a.mov_i(4, NPLATS)

    a.label('lc_loop')
    a.ldr(5, 3, 0)                     # platform x
    a.ldr(6, 3, 4)                     # platform y
    a.cmp_r(6, 2)
    a.b('lc_next', 'lt')               # platform above previous feet
    a.cmp_r(6, 1)
    a.b('lc_next', 'gt')               # platform below new feet
    a.add_i(7, 5, PLAT_W)
    a.cmp_r(0, 7)
    a.b('lc_next', 'ge')               # player right of platform
    a.add_i(8, 0, PW)
    a.cmp_r(8, 5)
    a.b('lc_next', 'le')               # player left of platform

    a.sub_i(6, 6, PH)
    a.mov_shift(6, 6, 0, 8)            # (plat_y - PH) << 8
    a.ldr_lit(0, V_PY)
    a.str(6, 0, 0)
    a.ldr_lit(0, V_VY)
    a.ldr_lit(1, BOUNCE_NEG)
    a.str(1, 0, 0)
    a.b('lc_done')

    a.label('lc_next')
    a.add_i(3, 3, 8)
    a.subs_i(4, 4, 1)
    a.b('lc_loop', 'ne')

    a.label('lc_done')
    a.pop(0x87F0)

    # ======================================================================
    # gen_platforms: keep ~140 px of platforms above the camera
    # ======================================================================
    a.label('gen_platforms')
    a.push(0x40F0)                     # {r4-r7, lr}
    a.label('gp_loop')
    a.ldr_lit(0, V_TOPY)
    a.ldr(4, 0, 0)
    a.ldr_lit(1, V_CAM)
    a.ldr(1, 1, 0)
    a.mov_shift(1, 1, 2, 8)
    a.sub_i(1, 1, 140)
    a.cmp_r(4, 1)
    a.b('gp_done', 'le')

    a.bl('rand_next')
    # x = clamp(prev_x + rand(-56..56), 0, 240 - PLAT_W)
    a.mov_shift(5, 0, 0, 16)
    a.mov_shift(5, 5, 1, 16)
    a.ldr_lit(1, 113)
    a.mul(5, 5, 1)
    a.mov_shift(5, 5, 1, 16)
    a.sub_i(5, 5, 56)
    a.ldr_lit(1, V_TOPX)
    a.ldr(2, 1, 0)
    a.add_r(5, 5, 2)
    a.cmp_i(5, 0)
    a.mov_i(5, 0, cond='lt')
    a.cmp_i(5, 240 - PLAT_W)
    a.mov_i(5, 240 - PLAT_W, cond='gt')
    a.str(5, 1, 0)

    # spacing = 38 + rand(0..12)
    a.mov_shift(6, 0, 1, 16)
    a.ldr_lit(1, 13)
    a.mul(6, 6, 1)
    a.mov_shift(6, 6, 1, 16)
    a.add_i(6, 6, 38)
    a.sub_r(4, 4, 6)                   # new y

    # store in the ring buffer
    a.ldr_lit(1, V_INS)
    a.ldr(2, 1, 0)
    a.ldr_lit(3, V_PLATS)
    a.mov_shift(0, 2, 0, 3)
    a.add_r(3, 3, 0)
    a.str(5, 3, 0)
    a.str(4, 3, 4)
    a.add_i(2, 2, 1)
    a.cmp_i(2, NPLATS)
    a.mov_i(2, 0, cond='ge')
    a.str(2, 1, 0)

    a.ldr_lit(0, V_TOPY)
    a.str(4, 0, 0)
    a.b('gp_loop')

    a.label('gp_done')
    a.pop(0x80F0)

    # ======================================================================
    # rand_next: LCG, returns the new state in r0
    # ======================================================================
    a.label('rand_next')
    a.ldr_lit(0, V_RAND)
    a.ldr(1, 0, 0)
    a.ldr_lit(2, 1103515245)
    a.mul(1, 1, 2)
    a.ldr_lit(2, 12345)
    a.add_r(1, 1, 2)
    a.str(1, 0, 0)
    a.mov_r(0, 1)
    a.ret()

    # ======================================================================
    # reset_game
    # ======================================================================
    a.label('reset_game')
    a.push(0x40F0)

    a.ldr_lit(0, V_PX)
    a.ldr_lit(1, 120 << 8)
    a.str(1, 0, 0)

    a.ldr_lit(0, V_PY)
    a.ldr_lit(1, START_Y << 8)
    a.str(1, 0, 0)
    a.ldr_lit(0, V_PPY)
    a.str(1, 0, 0)

    a.ldr_lit(0, V_VY)
    a.mov_i(1, 0)
    a.str(1, 0, 0)

    a.ldr_lit(0, V_CAM)
    a.ldr_lit(1, (START_Y - 56) << 8)
    a.str(1, 0, 0)

    a.ldr_lit(0, V_BEST)
    a.ldr_lit(1, START_Y)
    a.str(1, 0, 0)

    a.mov_i(1, 0)
    a.ldr_lit(0, V_SCORE)
    a.str(1, 0, 0)
    a.ldr_lit(0, V_STATE)
    a.str(1, 0, 0)
    a.ldr_lit(0, V_DIRX)
    a.str(1, 0, 0)
    a.ldr_lit(0, V_KEYS)
    a.str(1, 0, 0)
    a.ldr_lit(0, V_EDGE)
    a.str(1, 0, 0)
    a.ldr_lit(0, V_PREV)               # EWRAM holds junk right after power-on
    a.str(1, 0, 0)
    a.ldr_lit(0, V_ARM)
    a.str(1, 0, 0)
    a.ldr_lit(0, V_HOLD)
    a.str(1, 0, 0)

    a.ldr_lit(0, V_RAND)
    a.ldr_lit(1, 0x1234ABCD)
    a.str(1, 0, 0)

    a.ldr_lit(0, V_TOPX)
    a.ldr_lit(1, 100)
    a.str(1, 0, 0)

    # 14 platforms, 46 px apart, random-walked horizontally
    a.mov_i(4, 0)
    a.label('rg_loop')
    a.mov_i(1, 46)
    a.mul(5, 4, 1)
    a.ldr_lit(1, 960)
    a.sub_r(5, 1, 5)                   # y = 960 - i * 46

    a.ldr_lit(1, V_TOPX)
    a.ldr(6, 1, 0)                     # x = previous x
    a.cmp_i(4, 0)
    a.b('rg_store', 'eq')

    a.bl('rand_next')
    a.mov_shift(2, 0, 0, 16)
    a.mov_shift(2, 2, 1, 16)
    a.ldr_lit(1, 113)
    a.mul(2, 2, 1)
    a.mov_shift(2, 2, 1, 16)
    a.sub_i(2, 2, 56)
    a.add_r(6, 6, 2)
    a.cmp_i(6, 0)
    a.mov_i(6, 0, cond='lt')
    a.cmp_i(6, 240 - PLAT_W)
    a.mov_i(6, 240 - PLAT_W, cond='gt')
    a.ldr_lit(1, V_TOPX)
    a.str(6, 1, 0)

    a.label('rg_store')
    a.ldr_lit(1, V_PLATS)
    a.mov_shift(0, 4, 0, 3)
    a.add_r(1, 1, 0)
    a.str(6, 1, 0)
    a.str(5, 1, 4)

    a.add_i(4, 4, 1)
    a.cmp_i(4, NPLATS)
    a.b('rg_loop', 'lt')

    a.ldr_lit(0, V_INS)
    a.mov_i(1, 0)
    a.str(1, 0, 0)
    a.ldr_lit(0, V_TOPY)
    a.ldr_lit(1, 960 - (NPLATS - 1) * 46)
    a.str(1, 0, 0)

    # --- paint the first play frame completely ---------------------------
    a.bl('draw_sky')
    a.bl('draw_stars')
    a.bl('draw_hud')
    a.bl('draw_platforms')
    a.bl('draw_player')

    a.ldr_lit(0, V_CAM)
    a.ldr(0, 0, 0)
    a.mov_shift(0, 0, 2, 8)
    a.ldr_lit(1, V_PCAM)
    a.str(0, 1, 0)

    a.ldr_lit(0, V_SCORE)
    a.ldr(0, 0, 0)
    a.ldr_lit(1, V_DSCORE)
    a.str(0, 1, 0)
    a.pop(0x80F0)

    # ======================================================================
    # draw_game: incremental redraw.  Only the objects that can move are
    # erased (painted with the sky gradient) and drawn again; the HUD is
    # repainted only when the score changes.  This keeps every frame far
    # shorter than a full 240x160 repaint, so nothing tears or lags.
    # ======================================================================
    a.label('draw_game')
    a.push(0x4000)

    # --- HUD, only when the score changed -------------------------------
    a.ldr_lit(0, V_SCORE)
    a.ldr(0, 0, 0)
    a.ldr_lit(1, V_DSCORE)
    a.ldr(1, 1, 0)
    a.cmp_r(0, 1)
    a.b('dg_hud_done', 'eq')
    a.bl('draw_hud')
    a.ldr_lit(0, V_SCORE)
    a.ldr(0, 0, 0)
    a.ldr_lit(1, V_DSCORE)
    a.str(0, 1, 0)
    a.label('dg_hud_done')

    # --- wipe the previous frame's objects ------------------------------
    a.bl('erase_stars')
    a.bl('erase_platforms')
    a.bl('erase_player')

    # --- draw the current frame -----------------------------------------
    a.bl('draw_stars')
    a.bl('draw_platforms')
    a.bl('draw_player')

    a.ldr_lit(0, V_CAM)
    a.ldr(0, 0, 0)
    a.mov_shift(0, 0, 2, 8)
    a.ldr_lit(1, V_PCAM)
    a.str(0, 1, 0)
    a.pop(0x8000)

    # ======================================================================
    # erase_rect(x r0, y r1, w r2, h r3)
    # Repaint a clipped rectangle with the sky gradient, so the objects of
    # the previous frame disappear cleanly.
    # ======================================================================
    a.label('erase_rect')
    a.push(0x4FF0)                     # {r4-r11, lr}
    a.mov_r(4, 0)                      # x
    a.mov_r(5, 1)                      # y
    a.mov_r(6, 2)                      # w
    a.mov_r(7, 3)                      # h
    a.cmp_i(7, 0)
    a.b('er_done', 'le')
    a.cmp_i(6, 0)
    a.b('er_done', 'le')

    a.cmp_i(5, 12)                     # clip the HUD strip
    a.b('er_x', 'ge')
    a.mov_r(0, 5)
    a.sub_i(0, 0, 12)
    a.add_r(7, 7, 0)
    a.mov_i(5, 12)
    a.label('er_x')
    a.cmp_i(7, 0)
    a.b('er_done', 'le')

    a.cmp_i(5, 160)
    a.b('er_done', 'ge')
    a.add_r(0, 5, 7)
    a.cmp_i(0, 160)
    a.b('er_y', 'le')
    a.mov_i(0, 160)
    a.sub_r(7, 0, 5)
    a.label('er_y')

    a.cmp_i(4, 0)
    a.b('er_xl', 'ge')
    a.add_r(6, 6, 4)
    a.mov_i(4, 0)
    a.label('er_xl')
    a.cmp_i(6, 0)
    a.b('er_done', 'le')
    a.cmp_i(4, 240)
    a.b('er_done', 'ge')
    a.add_r(0, 4, 6)
    a.cmp_i(0, 240)
    a.b('er_xr', 'le')
    a.mov_i(0, 240)
    a.sub_r(6, 0, 4)
    a.label('er_xr')

    a.mov_i(0, 480)
    a.mul(0, 5, 0)                     # y * 480
    a.mov_shift(1, 4, 0, 1)            # x * 2
    a.add_r(0, 0, 1)
    a.ldr_lit(8, 0x06000000)
    a.add_r(8, 8, 0)
    a.mov_r(11, 8)                     # row base
    a.ldr_lit(9, tab_sky)

    a.label('er_row')
    a.mov_r(8, 11)                     # cursor = start of this row
    a.mov_shift(0, 5, 2, 4)            # band = y / 16
    a.ldr_r(0, 9, 0, shift=2)          # band colour
    a.mov_r(10, 6)
    a.label('er_px')
    a.strh(0, 8, 2, post=True)
    a.subs_i(10, 10, 1)
    a.b('er_px', 'ne')
    a.add_i(11, 11, 480)
    a.add_i(5, 5, 1)
    a.subs_i(7, 7, 1)
    a.b('er_row', 'ne')
    a.label('er_done')
    a.pop(0x8FF0)

    # ======================================================================
    # erasers for the three object layers
    # ======================================================================
    a.label('erase_player')
    a.push(0x4000)
    a.ldr_lit(0, V_PSX)
    a.ldr(0, 0, 0)
    a.ldr_lit(1, V_PSY)
    a.ldr(1, 1, 0)
    a.mov_i(2, 12)
    a.mov_i(3, 19)
    a.bl('erase_rect')
    a.pop(0x8000)

    a.label('erase_platforms')
    a.push(0x4FF0)
    a.ldr_lit(0, V_PCAM)
    a.ldr(10, 0, 0)
    a.ldr_lit(8, V_PLATS)
    a.mov_i(7, NPLATS)
    a.label('ep_loop')
    a.ldr(4, 8, 0)                     # x
    a.ldr(5, 8, 4)                     # world y
    a.sub_r(5, 5, 10)
    a.cmp_i(5, 0)
    a.b('ep_next', 'lt')
    a.cmp_i(5, 152)
    a.b('ep_next', 'gt')
    a.mov_r(0, 4)
    a.mov_r(1, 5)
    a.mov_i(2, PLAT_W)
    a.mov_i(3, PLAT_H)
    a.bl('erase_rect')
    a.label('ep_next')
    a.add_i(8, 8, 8)
    a.subs_i(7, 7, 1)
    a.b('ep_loop', 'ne')
    a.pop(0x8FF0)

    a.label('erase_stars')
    a.push(0x41F0)
    a.ldr_lit(8, tab_stars)
    a.mov_i(7, 48)
    a.ldr_lit(0, V_PCAM)
    a.ldr(5, 0, 0)
    a.mov_shift(5, 5, 1, 1)            # old camera / 2 (pixels: V_PCAM >> 1)
    a.label('es_loop')
    a.ldr(3, 8, 0)
    a.and_i(6, 3, 0xFF)                # x
    a.mov_shift(3, 3, 1, 8)            # y
    a.sub_r(3, 3, 5)
    a.and_i(3, 3, 0xFF)                # wrapped screen y
    a.cmp_i(3, 152)
    a.b('es_next', 'hi')
    a.mov_r(0, 6)
    a.mov_r(1, 3)
    a.mov_i(2, 2)
    a.mov_i(3, 2)
    a.bl('erase_rect')
    a.label('es_next')
    a.add_i(8, 8, 4)
    a.subs_i(7, 7, 1)
    a.b('es_loop', 'ne')
    a.pop(0x81F0)

    # ======================================================================
    # draw_sky: 10 bands of 16 rows, written as 32-bit words
    # ======================================================================
    a.label('draw_sky')
    a.push(0x4070)                     # {r4-r6, lr}
    a.ldr_lit(0, 0x06000000)
    a.ldr_lit(1, tab_sky)
    a.mov_i(2, 10)
    a.label('sky_band')
    a.ldr(4, 1, 0)
    a.mov_shift(5, 4, 0, 16)
    a.orr_r(5, 4, 5)
    a.ldr_lit(6, 1920)                 # 16 rows * 120 words
    a.label('sky_words')
    a.str(5, 0, 4, post=True)
    a.subs_i(6, 6, 1)
    a.b('sky_words', 'ne')
    a.add_i(1, 1, 4)
    a.subs_i(2, 2, 1)
    a.b('sky_band', 'ne')
    a.pop(0x8070)

    # ======================================================================
    # draw_planet
    # ======================================================================
    a.label('draw_planet')
    a.push(0x4000)
    a.mov_i(0, 196)
    a.mov_i(1, 44)
    a.ldr_lit(2, tab_planet)
    a.ldr_lit(3, C_PLANET)
    a.bl('draw_disk')

    a.mov_i(0, 186)
    a.mov_i(1, 34)
    a.mov_i(2, 7)
    a.mov_i(3, 5)
    a.ldr_lit(4, C_CRATER)
    a.bl('blit_rect')

    a.mov_i(0, 200)
    a.mov_i(1, 47)
    a.mov_i(2, 5)
    a.mov_i(3, 4)
    a.ldr_lit(4, C_CRATER)
    a.bl('blit_rect')

    a.mov_i(0, 190)
